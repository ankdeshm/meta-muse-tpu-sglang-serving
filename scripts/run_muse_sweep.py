#!/usr/bin/env python3
"""SGLang-TorchTPU serving sweep for Meta Muse models (Muse-Glimmer-30B & Muse-Spark-Open-816B-A42B).

Supports:
  * Single-server single-host sweeps (`FORCE_SINGLE_HOST=1`),
  * Multi-replica colocated single-host sweeps (`replicas > 1`: independent servers pinned via `base_gpu_id`
    and `SGLANG_TPU_PD_COLOCATED=1`, fronted by `muse_multi_replica_proxy.py` async least-inflight gateway),
  * Multi-host slice sweeps (`nnodes > 1` using GKE `TPU_WORKER_ID` / `TPU_WORKER_HOSTNAMES`),
  * Host-RAM `/dev/shm` staging OR direct GCSFuse mount (`use_gcsfuse: true` + `weight_loader_drop_cache_after_load`),
  * Speculative decoding (`DFLASH` with `Muse-Glimmer-30B-assistant` or `RadixArk/Muse-Spark-Open-DFlash2`).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
import urllib.request

SGL_ROOT = Path("/workspace/sglang")
RECIPE_DIR = SGL_ROOT / "benchmark/tpu/recipe/configs/muse_custom"
KILL_PATTERN = (
    r"sglang::|sglang\.launch_server|benchmark\.tpu\.launch_server|"
    r"sglang\.benchmark\.serving|muse_multi_replica_proxy"
)

RECIPE_TEMPLATE = '''"""Generated by run_muse_sweep.py: {name}."""
import json
from copy import deepcopy

from benchmark.tpu.recipe.configs.base import _FP8_BASE_CONFIG, LIBTPU_FLAGS

CONFIG = deepcopy(_FP8_BASE_CONFIG)
CONFIG["server_args"].update(json.loads({server_args!r}))
CONFIG["runtime_env"].update(json.loads({runtime_env!r}))
for _k in json.loads({drop_server_args!r}):
    CONFIG["server_args"].pop(_k, None)
_extra_libtpu = {extra_libtpu!r}
if _extra_libtpu:
    CONFIG["runtime_env"]["LIBTPU_INIT_ARGS"] = " ".join(LIBTPU_FLAGS + tuple(_extra_libtpu))
'''


def log(msg: str) -> None:
    rank = os.environ.get("TPU_WORKER_ID", "0")
    print(f"[{dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}][muse-sweep][w{rank}] {msg}", flush=True)


def gcs_to_fuse_path(gcs_uri: str, fuse_root: str = "/models") -> Path:
    # gs://<bucket>/<relpath> -> /models/<relpath>
    without_scheme = gcs_uri.replace("gs://", "", 1)
    rel = without_scheme.split("/", 1)[1] if "/" in without_scheme else ""
    return Path(fuse_root) / rel


def stage_model(gcs_uri: str, local_dir: Path) -> float:
    marker = local_dir / ".staged"
    if marker.exists():
        return 0.0
    local_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    subprocess.run(
        ["gcloud", "storage", "cp", "-r", "--no-user-output-enabled", f"{gcs_uri.rstrip('/')}/*", str(local_dir)],
        check=True,
    )
    marker.write_text("ok\n")
    return time.time() - t0


def wait_ready(port: int, procs: list[subprocess.Popen], timeout_s: float) -> bool:
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if any(p.poll() is not None for p in procs):
            return False
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/health_generate", timeout=60) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            pass
        time.sleep(15)
    return False


def stop_servers(procs: list[subprocess.Popen]) -> None:
    for proc in procs:
        if proc is not None and proc.poll() is None:
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except Exception:
                pass
    for proc in procs:
        if proc is not None and proc.poll() is None:
            try:
                proc.wait(timeout=60)
            except Exception:
                try:
                    os.killpg(proc.pid, signal.SIGKILL)
                except Exception:
                    pass
    subprocess.run(["pkill", "-9", "-f", KILL_PATTERN], check=False)
    time.sleep(25)


def sanity_generate(port: int, served_name: str) -> dict:
    body = {
        "model": served_name or "default",
        "messages": [{"role": "user", "content": "In one short sentence: what is the capital of France?"}],
        "max_tokens": 256,
        "temperature": 0,
    }
    req = urllib.request.Request(
        f"http://127.0.0.1:{port}/v1/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=600) as resp:
            out = json.loads(resp.read().decode())
        msg = out["choices"][0]["message"]
        content = msg.get("content") or ""
        return {
            "ok": True,
            "latency_s": round(time.time() - t0, 2),
            "content": content[:600],
            "content_tail": content[-300:],
            "reasoning_content": (msg.get("reasoning_content") or "")[:600],
            "usage": out.get("usage"),
        }
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {exc}"[:400]}


def server_info(server_log: Path) -> list[str]:
    keys = (
        "max_total_num_tokens",
        "KV Cache is allocated",
        "Memory pool end",
        "avail mem",
        "SWA",
        "max_running_requests",
        "Load weight end",
        "accept",
        "draft",
    )
    lines = []
    try:
        for line in server_log.read_text(errors="replace").splitlines():
            if ("TP0" in line or "Schedule" in line) and any(k in line for k in keys) and len(lines) < 25:
                lines.append(line[-400:])
    except Exception:
        pass
    return lines


def run_cell(
    port: int,
    tokenizer: str,
    served_name: str,
    inp: int,
    out: int,
    conc: int,
    out_file: Path,
    extra_args: list[str],
    timeout_s: int = 1500,
) -> dict:
    if inp >= 100000:
        nprompts = max(conc, 2)
    elif inp > 16384:
        nprompts = max(2 * conc, 3)
    else:
        nprompts = max(4 * conc, 8)
    cmd = [
        sys.executable,
        "-m",
        "sglang.benchmark.serving",
        "--backend",
        "sglang",
        "--base-url",
        f"http://127.0.0.1:{port}",
        "--dataset-name",
        "random",
        "--random-input-len",
        str(inp),
        "--random-output-len",
        str(out),
        "--random-range-ratio",
        "1.0",
        "--num-prompts",
        str(nprompts),
        "--max-concurrency",
        str(conc),
        "--tokenizer",
        tokenizer,
        "--output-file",
        str(out_file),
        "--warmup-requests",
        "1",
        *extra_args,
    ]
    if served_name:
        cmd += ["--model", served_name]
    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_s)
    row = {
        "input_len": inp,
        "output_len": out,
        "concurrency": conc,
        "num_prompts": nprompts,
        "return_code": proc.returncode,
        "wall_s": round(time.time() - t0, 1),
    }
    metrics = {}
    if out_file.exists():
        lines = [l for l in out_file.read_text().splitlines() if l.strip()]
        if lines:
            try:
                metrics = json.loads(lines[-1])
            except Exception:
                metrics = {}
    keep = (
        "completed",
        "duration",
        "request_throughput",
        "input_throughput",
        "output_throughput",
        "total_throughput",
        "mean_ttft_ms",
        "median_ttft_ms",
        "p99_ttft_ms",
        "mean_tpot_ms",
        "median_tpot_ms",
        "p99_tpot_ms",
        "mean_itl_ms",
        "median_itl_ms",
        "p99_itl_ms",
        "mean_e2e_latency_ms",
        "median_e2e_latency_ms",
        "accept_length",
        "spec_accept_length",
        "total_input_tokens",
        "total_output_tokens",
        "max_concurrency",
    )
    row["metrics"] = {k: metrics[k] for k in keep if k in metrics}
    if proc.returncode != 0 or not row["metrics"]:
        row["error_tail"] = (proc.stdout[-1500:] + "\n" + proc.stderr[-2500:]).strip()
    return row


def fmt(v, nd=1) -> str:
    return "-" if v is None else (f"{v:,.{nd}f}" if isinstance(v, (int, float)) else str(v))


def write_summary(out_dir: Path, meta: dict, variants: list[dict]) -> None:
    hw = meta.get("hardware", {})
    chips = int(hw.get("chips", 4))
    payload = {"updated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(), **meta, "variants": variants}
    (out_dir / "summary.json").write_text(json.dumps(payload, indent=2))
    md = [
        f"# {meta['title']}",
        "",
        f"- **Updated (UTC):** `{payload['updated_at_utc']}`",
        f"- **Hardware:** {hw.get('desc', '')}; engine `SGLang-TorchTPU` (`{meta.get('image', '')}`).",
        f"- **Checkpoint:** `{meta['model_repo']}` (`{meta.get('model_gb', '?')}` GB).",
        "- **Method:** `python -m sglang.benchmark.serving --dataset-name random --random-range-ratio 1.0`, "
        "every request decodes exact `output_len` tokens (EOS ignored).",
        "",
        "| Variant | Layout / precision | In / Out | Conc. | Req/s | Output tok/s | Output tok/s/chip | Total tok/s "
        "| TTFT p50 / p99 (ms) | TPOT p50 / p99 (ms) | Spec accept len | Status |",
        "|---|---|---|---:|---:|---:|---:|---:|---|---|---:|---|",
    ]
    for v in variants:
        v_chips = float(v.get("chips_used") or chips)
        if not v.get("cells"):
            md.append(f"| `{v['name']}` | {v['desc']} | - | - | - | - | - | - | - | - | - | `{v['status']}` |")
            continue
        for c in v["cells"]:
            m = c.get("metrics", {})
            otps = m.get("output_throughput")
            acc = m.get("accept_length", m.get("spec_accept_length"))
            status = "PASS" if m and c["return_code"] == 0 else f"FAIL(rc={c['return_code']})"
            md.append(
                f"| `{v['name']}` | {v['desc']} | `{c['input_len']}` / `{c['output_len']}` | {c['concurrency']} | "
                f"{fmt(m.get('request_throughput'), 3)} | {fmt(otps)} | {fmt(otps / v_chips if otps else None)} | "
                f"{fmt(m.get('total_throughput'))} | {fmt(m.get('median_ttft_ms'), 0)} / {fmt(m.get('p99_ttft_ms'), 0)} | "
                f"{fmt(m.get('median_tpot_ms'), 2)} / {fmt(m.get('p99_tpot_ms'), 2)} | {fmt(acc, 2)} | `{status}` |"
            )
    md += ["", "## Variant status / boot info", ""]
    for v in variants:
        md.append(
            f"- `{v['name']}`: **{v['status']}**, server ready after `{v.get('server_ready_s', '-')}` s"
            + (f"; sanity: `{(v.get('sanity') or {}).get('content', '')[:160]!r}`" if v.get("sanity") else "")
        )
    (out_dir / "SUMMARY.md").write_text("\n".join(md) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--out-root", default="/models/benchmark-results")
    ap.add_argument("--only", default="")
    ap.add_argument("--tag-suffix", default="")
    ap.add_argument("--proxy-script", default="/sweep/muse_multi_replica_proxy.py")
    args = ap.parse_args()

    plan = json.loads(Path(args.plan).read_text())
    worker_id = int(os.environ.get("TPU_WORKER_ID", "0"))
    is_multihost = int(plan.get("nnodes", 1)) > 1
    run_id = os.environ.get("MUSE_RUN_TS") or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = Path(args.out_root) / f"{plan['tag']}{args.tag_suffix}_{run_id}"
    if worker_id == 0:
        out_dir.mkdir(parents=True, exist_ok=True)
    RECIPE_DIR.mkdir(parents=True, exist_ok=True)
    base_port = int(plan.get("port", 30000))
    meta = {k: plan[k] for k in ("title", "model_repo", "model_gb", "image", "hardware") if k in plan}
    meta["plan"] = plan
    meta["only"] = args.only
    meta["node"] = os.environ.get("NODE_NAME", "")
    results: list[dict] = []
    only = [s.strip() for s in args.only.split(",") if s.strip()]
    variants = plan["variants"]
    if only:
        by_name = {v["name"]: v for v in variants}
        variants = [by_name[n] for n in only if n in by_name]

    staged: dict[str, Path] = {}
    for var_idx, var in enumerate(variants):
        rec = {
            "name": var["name"],
            "desc": var["desc"],
            "chips_used": var.get("chips_used"),
            "replicas": var.get("replicas", 1),
            "status": "PENDING",
            "cells": [],
        }
        results.append(rec)
        if worker_id == 0:
            write_summary(out_dir, meta, results)
        procs: list[subprocess.Popen] = []
        ready_flag = out_dir / f".ready_{var_idx}_{var['name']}"
        done_flag = out_dir / f".done_{var_idx}_{var['name']}"
        try:
            if is_multihost:
                if worker_id == 0:
                    ready_flag.write_text("ready\n")
                else:
                    # Refresh directory listing so GCSFuse sees rank-0 barrier files
                    wait_t0 = time.time()
                    while time.time() - wait_t0 < 900:
                        names = set(os.listdir(out_dir)) if out_dir.exists() else set()
                        if ready_flag.name in names:
                            break
                        time.sleep(3)

            use_gcsfuse = bool(var.get("use_gcsfuse", plan.get("use_gcsfuse", False)))
            gcs = var.get("model_gcs", plan["model_gcs"])
            draft_gcs = var.get("draft_gcs")
            if use_gcsfuse:
                local = gcs_to_fuse_path(gcs)
                log(f"[{var['name']}] using GCSFuse path {local}")
                if draft_gcs:
                    if draft_gcs not in staged:
                        target_draft = Path("/dev/shm/models") / draft_gcs.rstrip("/").split("/")[-1]
                        log(f"staging draft {draft_gcs} -> {target_draft}")
                        stage_model(draft_gcs, target_draft)
                        staged[draft_gcs] = target_draft
                    draft_local = staged[draft_gcs]
                else:
                    draft_local = None
            else:
                needed = {gcs} | ({draft_gcs} if draft_gcs else set())
                for old_gcs, old_dir in list(staged.items()):
                    if old_gcs not in needed:
                        subprocess.run(["rm", "-rf", str(old_dir)], check=False)
                        staged.pop(old_gcs)
                for uri in sorted(needed):
                    if uri not in staged:
                        target_local = Path("/dev/shm/models") / uri.rstrip("/").split("/")[-1]
                        log(f"staging {uri} -> {target_local}")
                        secs = stage_model(uri, target_local)
                        staged[uri] = target_local
                        log(f"staged in {secs:.0f}s")
                local = staged[gcs]
                draft_local = staged[draft_gcs] if draft_gcs else None

            base_sa = {"model_path": str(local), "port": base_port, **plan.get("server_args", {}), **var.get("server_args", {})}
            if draft_local is not None:
                overrides = var.get("draft_config_overrides") or {}
                if overrides:
                    cfg_path = draft_local / "config.json"
                    cfg = json.loads(cfg_path.read_text())
                    changed = {k: v for k, v in overrides.items() if cfg.get(k) != v}
                    if changed:
                        cfg.update(changed)
                        cfg_path.write_text(json.dumps(cfg, indent=2))
                    rec["draft_config_overrides"] = overrides
                base_sa["speculative_draft_model_path"] = str(draft_local)

            nnodes = int(base_sa.get("nnodes", plan.get("nnodes", 1)))
            base_env: dict[str, str] = {}
            if nnodes == 1:
                base_env["FORCE_SINGLE_HOST"] = "1"
            else:
                base_env["DIST_PORT"] = str(10011 + var_idx * 10)
            base_env.update(plan.get("runtime_env", {}))
            base_env.update(var.get("runtime_env", {}))
            drop = list(plan.get("drop_server_args", [])) + list(var.get("drop_server_args", []))
            extra_libtpu = list(plan.get("extra_libtpu", [])) + list(var.get("extra_libtpu", []))
            replicas = int(var.get("replicas", 1))
            tp_size = int(base_sa.get("tp_size", 1))
            ready_timeout_s = float(var.get("ready_timeout_s", 5400))
            cell_timeout_s = int(var.get("cell_timeout_s", plan.get("cell_timeout_s", 1200)))

            t0 = time.time()
            if replicas > 1:
                gw_port = int(var.get("gateway_port", 29999))
                backend_urls = []
                for r in range(replicas):
                    r_port = base_port + r
                    r_gpu = r * tp_size
                    r_sa = dict(base_sa, port=r_port, base_gpu_id=r_gpu)
                    r_sa.pop("dp_size", None)
                    r_env = dict(
                        base_env,
                        SGLANG_TPU_PD_COLOCATED="1",
                        TORCH_TPU_TIER2_NAME=f"replica_{r_gpu}",
                        TORCH_TPU_INTERNAL_TIER2_COMPILATION_CACHE=f"replica_{r_gpu}",
                    )
                    mod = f"{var['name']}_r{r}.py"
                    (RECIPE_DIR / mod).write_text(
                        RECIPE_TEMPLATE.format(
                            name=f"{var['name']}_r{r}",
                            server_args=json.dumps(r_sa),
                            runtime_env=json.dumps(r_env),
                            drop_server_args=json.dumps(drop),
                            extra_libtpu=extra_libtpu,
                        )
                    )
                    slog = out_dir / f"server_{var['name']}_r{r}.log"
                    log(f"[{var['name']}] launching replica {r}/{replicas} on port {r_port} (base_gpu_id={r_gpu})")
                    p = subprocess.Popen(
                        [sys.executable, "-m", "benchmark.tpu.launch_server", "--config", f"recipe/configs/muse_custom/{mod}"],
                        cwd=str(SGL_ROOT),
                        stdout=open(slog, "w"),
                        stderr=subprocess.STDOUT,
                        start_new_session=True,
                        env={**os.environ, "HEALTH_TIMEOUT": str(int(ready_timeout_s))},
                    )
                    procs.append(p)
                    backend_urls.append(f"http://127.0.0.1:{r_port}")

                server_log = out_dir / f"server_{var['name']}_r0.log"
                rec["recipe"] = (RECIPE_DIR / f"{var['name']}_r0.py").read_text()
                all_ready = all(wait_ready(base_port + r, procs, ready_timeout_s) for r in range(replicas))
                if all_ready:
                    gw_log = out_dir / f"gateway_{var['name']}.log"
                    gw_proc = subprocess.Popen(
                        [
                            sys.executable,
                            args.proxy_script,
                            "--port",
                            str(gw_port),
                            "--backends",
                            ",".join(backend_urls),
                        ],
                        stdout=open(gw_log, "w"),
                        stderr=subprocess.STDOUT,
                        start_new_session=True,
                    )
                    procs.append(gw_proc)
                    ready = wait_ready(gw_port, procs, 60.0)
                else:
                    ready = False
                bench_port = gw_port
            else:
                mod = f"{var['name']}.py"
                (RECIPE_DIR / mod).write_text(
                    RECIPE_TEMPLATE.format(
                        name=var["name"],
                        server_args=json.dumps(base_sa),
                        runtime_env=json.dumps(base_env),
                        drop_server_args=json.dumps(drop),
                        extra_libtpu=extra_libtpu,
                    )
                )
                rec["recipe"] = (RECIPE_DIR / mod).read_text()
                server_log = out_dir / f"server_{var['name']}_w{worker_id}.log" if is_multihost else out_dir / f"server_{var['name']}.log"
                server_log.parent.mkdir(parents=True, exist_ok=True)
                log(f"[{var['name']}] launching server ({var['desc']})")
                p = subprocess.Popen(
                    [sys.executable, "-m", "benchmark.tpu.launch_server", "--config", f"recipe/configs/muse_custom/{mod}"],
                    cwd=str(SGL_ROOT),
                    stdout=open(server_log, "w"),
                    stderr=subprocess.STDOUT,
                    start_new_session=True,
                    env={**os.environ, "HEALTH_TIMEOUT": str(int(ready_timeout_s))},
                )
                procs.append(p)
                bench_port = base_port
                if worker_id == 0:
                    ready = wait_ready(bench_port, procs, ready_timeout_s)
                else:
                    # Nonzero multi-host worker: stay alive while local launch_server runs AND rank 0 hasn't signaled done
                    while p.poll() is None:
                        names = set(os.listdir(out_dir)) if out_dir.exists() else set()
                        if done_flag.name in names:
                            break
                        time.sleep(8)
                    stop_servers(procs)
                    continue

            rec["server_ready_s"] = round(time.time() - t0, 1)
            rec["server_info"] = server_info(server_log)
            if not ready:
                rec["status"] = "SERVER_FAILED"
                rec["server_log_tail"] = server_log.read_text(errors="replace")[-6000:] if server_log.exists() else ""
                log(f"[{var['name']}] server did not become ready ({rec['server_ready_s']}s)")
                if is_multihost:
                    done_flag.write_text("failed\n")
                stop_servers(procs)
                if is_multihost:
                    time.sleep(15)
                write_summary(out_dir, meta, results)
                continue

            log(f"[{var['name']}] ready after {rec['server_ready_s']}s")
            rec["sanity"] = sanity_generate(bench_port, base_sa.get("served_model_name", ""))
            log(f"[{var['name']}] sanity: {json.dumps(rec['sanity'])[:500]}")
            rec["status"] = "RUNNING"
            write_summary(out_dir, meta, results)
            bench_extra = list(plan.get("bench_extra", [])) + list(var.get("bench_extra", []))
            for inp, out, concs in var.get("workloads", plan["workloads"]):
                for conc in concs:
                    cell_file = out_dir / f"bench_{var['name']}_i{inp}_o{out}_c{conc}.jsonl"
                    log(f"[{var['name']}] bench in={inp} out={out} conc={conc}")
                    try:
                        cell = run_cell(
                            bench_port,
                            str(local),
                            base_sa.get("served_model_name", ""),
                            inp,
                            out,
                            conc,
                            cell_file,
                            bench_extra,
                            timeout_s=cell_timeout_s,
                        )
                    except subprocess.TimeoutExpired:
                        cell = {
                            "input_len": inp,
                            "output_len": out,
                            "concurrency": conc,
                            "return_code": -9,
                            "metrics": {},
                            "error_tail": f"client timeout after {cell_timeout_s}s",
                        }
                        # Kill stray client process if any
                        subprocess.run(["pkill", "-9", "-f", "sglang.benchmark.serving"], check=False)
                    rec["cells"].append(cell)
                    m = cell.get("metrics", {})
                    log(
                        f"[{var['name']}] -> rc={cell['return_code']} out_tok/s={m.get('output_throughput')} "
                        f"ttft_p50={m.get('median_ttft_ms')} tpot_p50={m.get('median_tpot_ms')} "
                        f"accept={m.get('accept_length', m.get('spec_accept_length'))}"
                    )
                    write_summary(out_dir, meta, results)
                    if any(pr.poll() is not None for pr in procs):
                        break
                if any(pr.poll() is not None for pr in procs):
                    rec["status"] = "SERVER_DIED"
                    rec["server_log_tail"] = server_log.read_text(errors="replace")[-6000:] if server_log.exists() else ""
                    break
            if rec["status"] == "RUNNING":
                rec["status"] = "DONE"
            rec["server_info"] = server_info(server_log)
            if is_multihost:
                done_flag.write_text("done\n")
            stop_servers(procs)
        except Exception as exc:
            rec["status"] = f"ERROR: {type(exc).__name__}: {exc}"[:400]
            log(f"[{var['name']}] {rec['status']}")
            if is_multihost and worker_id == 0:
                try:
                    done_flag.write_text("error\n")
                except Exception:
                    pass
            stop_servers(procs)
        if worker_id == 0:
            write_summary(out_dir, meta, results)
    log(f"sweep finished -> {out_dir}")
    return 0


