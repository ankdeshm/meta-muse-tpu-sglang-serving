def fmt(v, nd=1) -> str:
    return "-" if v is None else (f"{v:,.{nd}f}" if isinstance(v, (int, float)) else str(v))


def write_summary(out_dir: Path, meta: dict, variants: list[dict], worker_id: int = 0, nnodes: int = 1) -> None:
    hw = meta.get("hardware", {})
    chips = int(hw.get("chips", 4))
    now_iso = dt.datetime.now(dt.timezone.utc).isoformat()
    if worker_id > 0:
        w_payload = {"updated_at_utc": now_iso, "worker_id": worker_id, "variants": variants}
        (out_dir / f"summary_w{worker_id}.json").write_text(json.dumps(w_payload, indent=2))
        return

    merged = list(variants)
    seen = {v["name"] for v in merged}
    for wid in range(1, nnodes):
        w_fp = out_dir / f"summary_w{wid}.json"
        if w_fp.exists():
            try:
                w_data = json.loads(w_fp.read_text())
                for wv in w_data.get("variants", []):
                    if wv.get("name") not in seen:
                        merged.append(wv)
                        seen.add(wv["name"])
            except Exception:
                pass

    payload = {"updated_at_utc": now_iso, **meta, "variants": merged}
    (out_dir / "summary.json").write_text(json.dumps(payload, indent=2))
    md = [
        f"# {meta['title']}",
        "",
        f"- **Updated (UTC):** `{payload['updated_at_utc']}`",
        f"- **Hardware:** {hw.get('desc', '')}; engine `SGLang-TorchTPU` (`{meta.get('image', '')}`).",
        f"- **Checkpoint:** `{meta['model_repo']}` (`{meta.get('model_gb', '?')}` GB).",
        "- **Method:** `python -m sglang.benchmark.serving --dataset-name random --random-range-ratio 1.0`, "
        "every request decodes exact `output_len` tokens (EOS ignored).",
        "",
        "| Variant | Layout / precision | In / Out | Conc. | Req/s | Output tok/s | Output tok/s/chip | Total tok/s "
        "| TTFT p50 / p99 (ms) | TPOT p50 / p99 (ms) | Spec accept len | Status |",
        "|---|---|---|---:|---:|---:|---:|---:|---|---|---:|---|",
    ]
    for v in merged:
        v_chips = float(v.get("chips_used") or chips)
        if not v.get("cells"):
            md.append(f"| `{v['name']}` | {v['desc']} | - | - | - | - | - | - | - | - | - | `{v['status']}` |")
            continue
        for c in v["cells"]:
            m = c.get("metrics", {})
            otps = m.get("output_throughput")
            acc = m.get("accept_length", m.get("spec_accept_length"))
            status = "PASS" if m and c["return_code"] == 0 else f"FAIL(rc={c['return_code']})"
            md.append(
                f"| `{v['name']}` | {v['desc']} | `{c['input_len']}` / `{c['output_len']}` | {c['concurrency']} | "
                f"{fmt(m.get('request_throughput'), 3)} | {fmt(otps)} | {fmt(otps / v_chips if otps else None)} | "
                f"{fmt(m.get('total_throughput'))} | {fmt(m.get('median_ttft_ms'), 0)} / {fmt(m.get('p99_ttft_ms'), 0)} | "
                f"{fmt(m.get('median_tpot_ms'), 2)} / {fmt(m.get('p99_tpot_ms'), 2)} | {fmt(acc, 2)} | `{status}` |"
            )
    md += ["", "## Variant status / boot info", ""]
    for v in merged:
        md.append(
            f"- `{v['name']}`: **{v['status']}**, server ready after `{v.get('server_ready_s', '-')}` s"
            + (f"; sanity: `{(v.get('sanity') or {}).get('content', '')[:160]!r}`" if v.get("sanity") else "")
        )
    (out_dir / "SUMMARY.md").write_text("\n".join(md) + "\n")


def patch_jax011_pallas() -> None:
    """Fix JAX 0.11 removed pltpu.* aliases and preserve multi-host TPU bounds in launch_server."""
    subs = [
        ("pltpu.semaphore_signal(", "pl.semaphore_signal("),
        ("pltpu.semaphore_wait(", "pl.semaphore_wait("),
        ("pltpu.semaphore_read(", "pl.semaphore_read("),
        ("pltpu.DeviceIdType", "pl.DeviceIdType"),
        ("pltpu.semaphore(", "pl.semaphore("),
    ]
    rels = [
        "moe/pallas/fused_rs/gmm_fused_rs_nodedup.py",
        "k3_megakernel/kernel/collectives.py",
        "twolevel_allreduce.py",
    ]
    roots = [
        Path("/workspace/sglang/sglang_tpu"),
        Path("/workspace/sglang/build/lib/sglang_tpu"),
        Path("/usr/local/lib/python3.12/site-packages/sglang_tpu"),
    ]
    patched = 0
    for root in roots:
        for rel in rels:
            fp = root / rel
            if not fp.exists():
                continue
            orig = fp.read_text(encoding="utf-8", errors="replace")
            updated = orig
            for old, new in subs:
                updated = updated.replace(old, new)
            if updated != orig:
                fp.write_text(updated, encoding="utf-8")
                patched += 1
        nn_fp = root / "node_normalization.py"
        if nn_fp.exists():
            nn_orig = nn_fp.read_text(encoding="utf-8", errors="replace")
            target = 'child_env = dict(os.environ)\n    child_env["PYTHONPATH"]'
            replacement = (
                'child_env = dict(os.environ)\n'
                '    child_env.pop("TORCH_TPU_SLICEBUILDER_ADDRESSES", None)\n'
                '    child_env.pop("TORCH_TPU_TOPOLOGY", None)\n'
                '    child_env["PYTHONPATH"]'
            )
            if target in nn_orig and "TORCH_TPU_SLICEBUILDER_ADDRESSES" not in nn_orig.split("_query_local_device_coords")[1][:400]:
                nn_fp.write_text(nn_orig.replace(target, replacement, 1), encoding="utf-8")
                patched += 1
    ls_fp = SGL_ROOT / "benchmark/tpu/launch_server.py"
    if ls_fp.exists():
        ls_orig = ls_fp.read_text(encoding="utf-8", errors="replace")
        ls_target = '    if settings.get("tp_size", 1) > 1:\n        for key in ('
        ls_repl = '    if settings.get("tp_size", 1) > 1 and settings.get("nnodes", 1) == 1:\n        for key in ('
        if ls_target in ls_orig:
            ls_fp.write_text(ls_orig.replace(ls_target, ls_repl, 1), encoding="utf-8")
            patched += 1
    if patched:
        log(f"patched {patched} sglang_tpu files (JAX 0.11 Pallas + multi-host coordinate discovery)")


def execute_workload_list(
    rec: dict,
    workloads: list,
    bench_base_url: str,
    local_tokenizer: str,
    served_name: str,
    bench_extra: list[str],
    out_dir: Path,
    cell_timeout_s: int,
    procs: list[subprocess.Popen],
    server_logs: list[Path],
    on_update,
) -> None:
    for inp, out, concs in workloads:
        for conc in concs:
            cell_file = out_dir / f"bench_{rec['name']}_i{inp}_o{out}_c{conc}.jsonl"
            log(f"[{rec['name']}] bench in={inp} out={out} conc={conc}")
            try:
                cell = run_cell(
                    bench_base_url,
                    local_tokenizer,
                    served_name,
                    inp,
                    out,
                    conc,
                    cell_file,
                    bench_extra,
                    timeout_s=cell_timeout_s,
                )
            except subprocess.TimeoutExpired:
                cell = {
                    "input_len": inp,
                    "output_len": out,
                    "concurrency": conc,
                    "return_code": -9,
                    "metrics": {},
                    "error_tail": f"client timeout after {cell_timeout_s}s",
                }
                subprocess.run(["pkill", "-9", "-f", "sglang.benchmark.serving"], check=False)
            rec["cells"].append(cell)
            m = cell.get("metrics", {})
            log(
                f"[{rec['name']}] -> rc={cell['return_code']} out_tok/s={m.get('output_throughput')} "
                f"ttft_p50={m.get('median_ttft_ms')} tpot_p50={m.get('median_tpot_ms')} "
                f"accept={m.get('accept_length', m.get('spec_accept_length'))}"
            )
            on_update()
            if any(pr.poll() is not None for pr in procs):
                break
        if any(pr.poll() is not None for pr in procs):
            rec["status"] = "SERVER_DIED"
            rec["server_log_tail"] = server_logs[0].read_text(errors="replace")[-6000:] if server_logs[0].exists() else ""
            break


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--out-root", default="/models/benchmark-results")
    ap.add_argument("--only", default="")
    ap.add_argument("--tag-suffix", default="")
    ap.add_argument("--proxy-script", default="/sweep/muse_multi_replica_proxy.py")
    args = ap.parse_args()

    patch_jax011_pallas()
    plan = json.loads(Path(args.plan).read_text())
    worker_id = int(os.environ.get("JOB_COMPLETION_INDEX", os.environ.get("TPU_WORKER_ID", "0")))
    nnodes_plan = int(plan.get("nnodes", 1))
    is_multihost_job = nnodes_plan > 1
    raw_whosts = [h.strip() for h in os.environ.get("MUSE_WORKER_HOSTS", os.environ.get("TPU_WORKER_HOSTNAMES", "")).split(",") if h.strip()]
    whosts = raw_whosts if raw_whosts else ["127.0.0.1"]
    coord_port = int(plan.get("coord_port", 29599))
    coord_host = whosts[0]

    if is_multihost_job:
        if worker_id == 0:
            start_coord_server(coord_port, nnodes_plan)
            log(f"started TCP coordinator on 0.0.0.0:{coord_port} for {nnodes_plan} hosts (hosts={whosts})")
        dns_deadline = time.time() + 300
        while time.time() < dns_deadline:
            try:
                socket.gethostbyname(coord_host)
                break
            except socket.gaierror:
                time.sleep(2.0)
        multihost_barrier(coord_host, coord_port, "boot", worker_id, timeout_s=600)
        log(f"all {nnodes_plan} workers passed boot barrier")

    run_id = os.environ.get("MUSE_RUN_TS") or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = Path(args.out_root) / f"{plan['tag']}{args.tag_suffix}_{run_id}"
    out_dir.mkdir(parents=True, exist_ok=True)
    RECIPE_DIR.mkdir(parents=True, exist_ok=True)

    base_port = int(plan.get("port", 30000))
    meta = {k: plan[k] for k in ("title", "model_repo", "model_gb", "image", "hardware") if k in plan}
    meta["plan"] = plan
    meta["only"] = args.only
    meta["node"] = os.environ.get("NODE_NAME", "")
    if is_multihost_job:
        meta["worker_hosts"] = whosts
    results: list[dict] = []
    only = [s.strip() for s in args.only.split(",") if s.strip()]
    variants = plan["variants"]
    if only:
        by_name = {v["name"]: v for v in variants}
        variants = [by_name[n] for n in only if n in by_name]

    staged: dict[str, Path] = {}
    for var_idx, var in enumerate(variants):
        affinity = var.get("worker_affinity")
        is_dist_gw = bool(var.get("distributed_gateway", False))
        var_nnodes = int(var.get("nnodes", var.get("server_args", {}).get("nnodes", 1 if (affinity is not None or is_dist_gw) else nnodes_plan)))
        is_var_multihost = is_multihost_job and (var_nnodes > 1 or is_dist_gw)

        if affinity is not None and int(affinity) != worker_id:
            log(f"[{var['name']}] skipping on worker {worker_id} (worker_affinity={affinity})")
            continue

        is_var_leader = (worker_id == int(affinity)) if affinity is not None else (worker_id == 0)

        rec = {
            "name": var["name"],
            "desc": var["desc"],
            "chips_used": var.get("chips_used"),
            "replicas": var.get("replicas", int(var.get("replicas_per_host", 1)) * nnodes_plan if is_dist_gw else 1),
            "worker_id": worker_id,
            "status": "PENDING",
            "cells": [],
        }
        if is_var_leader:
            results.append(rec)
            write_summary(out_dir, meta, results, worker_id=worker_id, nnodes=nnodes_plan)
        procs: list[subprocess.Popen] = []
        try:
            use_gcsfuse = bool(var.get("use_gcsfuse", plan.get("use_gcsfuse", False)))
            do_prefetch = bool(var.get("prefetch_pagecache", plan.get("prefetch_pagecache", False)))
            gcs = var.get("model_gcs", plan["model_gcs"])
            draft_gcs = var.get("draft_gcs")
            if use_gcsfuse:
                local = gcs_to_fuse_path(gcs)
                log(f"[{var['name']}] using GCSFuse path {local}")
                if do_prefetch:
                    prefetch_gcsfuse_pagecache(local)
                if draft_gcs:
                    if draft_gcs not in staged:
                        target_draft = Path("/dev/shm/models") / draft_gcs.rstrip("/").split("/")[-1]
                        log(f"staging draft {draft_gcs} -> {target_draft}")
                        stage_model(draft_gcs, target_draft)
                        staged[draft_gcs] = target_draft
                    draft_local = staged[draft_gcs]
                else:
                    draft_local = None
            else:
                needed = {gcs} | ({draft_gcs} if draft_gcs else set())
                for old_gcs, old_dir in list(staged.items()):
                    if old_gcs not in needed:
                        subprocess.run(["rm", "-rf", str(old_dir)], check=False)
                        staged.pop(old_gcs)
                for uri in sorted(needed):
                    if uri not in staged:
                        target_local = Path("/dev/shm/models") / uri.rstrip("/").split("/")[-1]
                        log(f"staging {uri} -> {target_local}")
                        secs = stage_model(uri, target_local)
                        staged[uri] = target_local
                        log(f"staged in {secs:.0f}s")
                local = staged[gcs]
                draft_local = staged[draft_gcs] if draft_gcs else None

            base_sa = {"model_path": str(local), "port": base_port, **plan.get("server_args", {}), **var.get("server_args", {})}
            if draft_local is not None:
                overrides = var.get("draft_config_overrides") or {}
                if overrides:
                    cfg_path = draft_local / "config.json"
                    cfg = json.loads(cfg_path.read_text())
                    changed = {k: v for k, v in overrides.items() if cfg.get(k) != v}
                    if changed:
                        cfg.update(changed)
                        cfg_path.write_text(json.dumps(cfg, indent=2))
                    rec["draft_config_overrides"] = overrides
                base_sa["speculative_draft_model_path"] = str(draft_local)

            base_env: dict[str, str | None] = {}
            if var_nnodes == 1:
                base_sa.pop("nnodes", None)
                base_sa.pop("node_rank", None)
                base_sa.pop("dist_init_addr", None)
                base_env["FORCE_SINGLE_HOST"] = "1"
            else:
                dist_port = 10011 + var_idx * 10
                sb_port = 8070 + var_idx * 20
                base_sa["nnodes"] = var_nnodes
                base_sa["node_rank"] = worker_id
                base_sa["dist_init_addr"] = f"{whosts[0]}:{dist_port}"
                base_sa.setdefault("dist_timeout", 600)
                base_env["TORCH_TPU_BASE_PORT"] = str(sb_port)
            base_env.update(plan.get("runtime_env", {}))
            base_env.update(var.get("runtime_env", {}))
            if var_nnodes == 1:
                # Ensure single-host / distributed-gateway workers ignore multi-host slice env overrides
                for k in ("TORCH_TPU_TOPOLOGY", "TPU_HOST_BOUNDS", "TPU_CHIPS_PER_HOST_BOUNDS", "TORCH_TPU_DEVICES_PER_HOST"):
                    base_env.pop(k, None)
                base_env["FORCE_SINGLE_HOST"] = "1"
            else:
                # Clear FORCE_SINGLE_HOST=1 inherited from single-host base recipes (e.g. muse_spark/server.py)
                base_env["FORCE_SINGLE_HOST"] = None

            drop = list(plan.get("drop_server_args", [])) + list(var.get("drop_server_args", []))
            extra_args = list(plan.get("extra_args", [])) + list(var.get("extra_args", []))
            if var_nnodes == 1:
                extra_args = [x for x in extra_args if x != "--no-tpu-node-normalization"]
            extra_libtpu = list(plan.get("extra_libtpu", [])) + list(var.get("extra_libtpu", []))
            base_recipe = str(var.get("base_recipe", plan.get("base_recipe", "")))
            replicas = int(var.get("replicas", 1))
            rph = int(var.get("replicas_per_host", replicas))
            tp_size = int(base_sa.get("tp_size", 1))
            ready_timeout_s = float(var.get("ready_timeout_s", plan.get("ready_timeout_s", 7200)))
            cell_timeout_s = int(var.get("cell_timeout_s", plan.get("cell_timeout_s", 1200)))

            if is_var_multihost:
                multihost_barrier(coord_host, coord_port, f"pre_launch_{var_idx}", worker_id, timeout_s=3600)

            t0 = time.time()
            if is_dist_gw:
                gw_port = int(var.get("gateway_port", 29999))
                server_logs = []
                for r in range(rph):
                    r_port = base_port + r
                    r_gpu = r * tp_size
                    r_sa = dict(base_sa, host="0.0.0.0", port=r_port)
                    r_sa.pop("dp_size", None)
                    r_env = dict(base_env)
                    if rph > 1:
                        r_sa["base_gpu_id"] = r_gpu
                        r_env.update(
                            SGLANG_TPU_PD_COLOCATED="1",
                            TORCH_TPU_TIER2_NAME=f"replica_{r_gpu}",
                            TORCH_TPU_INTERNAL_TIER2_COMPILATION_CACHE=f"replica_{r_gpu}",
                        )
                    mod = f"{var['name']}_w{worker_id}_r{r}.py"
                    (RECIPE_DIR / mod).write_text(
                        RECIPE_TEMPLATE.format(
                            name=f"{var['name']}_w{worker_id}_r{r}",
                            base_recipe=base_recipe,
                            server_args=json.dumps(r_sa),
                            runtime_env=json.dumps(r_env),
                            drop_server_args=json.dumps(drop),
                            extra_args=json.dumps(extra_args),
                            extra_libtpu=extra_libtpu,
                        )
                    )
                    slog = out_dir / f"server_{var['name']}_w{worker_id}_r{r}.log"
                    server_logs.append(slog)
                    log(f"[{var['name']}] (dist_gw w{worker_id}) launching replica {r}/{rph} on 0.0.0.0:{r_port}")
                    p = subprocess.Popen(
                        [sys.executable, "-m", "benchmark.tpu.launch_server", "--config", f"recipe/configs/muse_custom/{mod}"],
                        cwd=str(SGL_ROOT),
                        stdout=open(slog, "w"),
                        stderr=subprocess.STDOUT,
                        start_new_session=True,
                        env={**os.environ, "HEALTH_TIMEOUT": str(int(ready_timeout_s))},
                    )
                    procs.append(p)
                rec["recipe"] = (RECIPE_DIR / f"{var['name']}_w{worker_id}_r0.py").read_text()
                local_ready = all(
                    wait_ready_any([f"http://127.0.0.1:{base_port + r}"], procs, ready_timeout_s) is not None
                    for r in range(rph)
                )
                if not local_ready:
                    log(f"[{var['name']}] local replica(s) failed on worker {worker_id}")
                    multihost_mark_done(coord_host, coord_port, var_idx, "failed")
                multihost_barrier(coord_host, coord_port, f"dist_gw_ready_{var_idx}", worker_id, timeout_s=int(ready_timeout_s) + 300)
                if is_var_leader:
                    if multihost_is_done(coord_host, coord_port, var_idx):
                        bench_base_url = None
                    else:
                        all_backends = [f"http://{h}:{base_port + r}" for h in whosts[:nnodes_plan] for r in range(rph)]
                        gw_log = out_dir / f"gateway_{var['name']}.log"
                        gw_proc = subprocess.Popen(
                            [
                                sys.executable,
                                args.proxy_script,
                                "--host",
                                "0.0.0.0",
                                "--port",
                                str(gw_port),
                                "--backends",
                                ",".join(all_backends),
                            ],
                            stdout=open(gw_log, "w"),
                            stderr=subprocess.STDOUT,
                            start_new_session=True,
                        )
                        procs.append(gw_proc)
                        bench_base_url = wait_ready_any([f"http://127.0.0.1:{gw_port}"], procs, 90.0)
                else:
                    while all(pr.poll() is None for pr in procs):
                        if multihost_is_done(coord_host, coord_port, var_idx):
                            break
                        time.sleep(5)
                    stop_servers(procs)
                    multihost_barrier(coord_host, coord_port, f"post_stop_{var_idx}", worker_id, timeout_s=600)
                    continue
            elif replicas > 1:
                gw_port = int(var.get("gateway_port", 29999))
                backend_urls = []
                for r in range(replicas):
                    r_port = base_port + r
                    r_gpu = r * tp_size
                    r_sa = dict(base_sa, port=r_port, base_gpu_id=r_gpu)
                    r_sa.pop("dp_size", None)
                    r_env = dict(
                        base_env,
                        SGLANG_TPU_PD_COLOCATED="1",
                        TORCH_TPU_TIER2_NAME=f"replica_{r_gpu}",
                        TORCH_TPU_INTERNAL_TIER2_COMPILATION_CACHE=f"replica_{r_gpu}",
                    )
                    mod = f"{var['name']}_r{r}.py"
                    (RECIPE_DIR / mod).write_text(
                        RECIPE_TEMPLATE.format(
                            name=f"{var['name']}_r{r}",
                            base_recipe=base_recipe,
                            server_args=json.dumps(r_sa),
                            runtime_env=json.dumps(r_env),
                            drop_server_args=json.dumps(drop),
                            extra_args=json.dumps(extra_args),
                            extra_libtpu=extra_libtpu,
                        )
                    )
                    slog = out_dir / f"server_{var['name']}_r{r}.log"
                    log(f"[{var['name']}] launching replica {r}/{replicas} on port {r_port} (base_gpu_id={r_gpu})")
                    p = subprocess.Popen(
                        [sys.executable, "-m", "benchmark.tpu.launch_server", "--config", f"recipe/configs/muse_custom/{mod}"],
                        cwd=str(SGL_ROOT),
                        stdout=open(slog, "w"),
                        stderr=subprocess.STDOUT,
                        start_new_session=True,
                        env={**os.environ, "HEALTH_TIMEOUT": str(int(ready_timeout_s))},
                    )
                    procs.append(p)
                    backend_urls.append(f"http://127.0.0.1:{r_port}")

                server_logs = [out_dir / f"server_{var['name']}_r0.log"]
                rec["recipe"] = (RECIPE_DIR / f"{var['name']}_r0.py").read_text()
                all_ready = all(
                    wait_ready_any([f"http://127.0.0.1:{base_port + r}"], procs, ready_timeout_s) is not None
                    for r in range(replicas)
                )
                if all_ready:
                    gw_log = out_dir / f"gateway_{var['name']}.log"
                    gw_proc = subprocess.Popen(
                        [
                            sys.executable,
                            args.proxy_script,
                            "--port",
                            str(gw_port),
                            "--backends",
                            ",".join(backend_urls),
                        ],
                        stdout=open(gw_log, "w"),
                        stderr=subprocess.STDOUT,
                        start_new_session=True,
                    )
                    procs.append(gw_proc)
                    bench_base_url = wait_ready_any([f"http://127.0.0.1:{gw_port}"], procs, 60.0)
                else:
                    bench_base_url = None
            else:
                mod = f"{var['name']}_w{worker_id}.py" if is_multihost_job else f"{var['name']}.py"
                (RECIPE_DIR / mod).write_text(
                    RECIPE_TEMPLATE.format(
                        name=var["name"],
                        base_recipe=base_recipe,
                        server_args=json.dumps(base_sa),
                        runtime_env=json.dumps(base_env),
                        drop_server_args=json.dumps(drop),
                        extra_args=json.dumps(extra_args),
                        extra_libtpu=extra_libtpu,
                    )
                )
                rec["recipe"] = (RECIPE_DIR / mod).read_text()
                server_log = out_dir / f"server_{var['name']}_w{worker_id}.log" if is_multihost_job else out_dir / f"server_{var['name']}.log"
                server_log.parent.mkdir(parents=True, exist_ok=True)
                server_logs = [out_dir / f"server_{var['name']}_w{i}.log" for i in range(nnodes_plan)] if is_var_multihost else [server_log]
                log(f"[{var['name']}] launching server (worker_id={worker_id}, {var['desc']})")
                p = subprocess.Popen(
                    [sys.executable, "-m", "benchmark.tpu.launch_server", "--config", f"recipe/configs/muse_custom/{mod}"],
                    cwd=str(SGL_ROOT),
                    stdout=open(server_log, "w"),
                    stderr=subprocess.STDOUT,
                    start_new_session=True,
                    env={**os.environ, "HEALTH_TIMEOUT": str(int(ready_timeout_s))},
                )
                procs.append(p)
                if is_var_leader:
                    candidate_urls = [f"http://127.0.0.1:{base_port}"]
                    if is_var_multihost:
                        candidate_urls += [f"http://{h}:{base_port}" for h in whosts]
                    bench_base_url = wait_ready_any(candidate_urls, procs, ready_timeout_s)
                else:
                    while p.poll() is None:
                        if multihost_is_done(coord_host, coord_port, var_idx):
                            break
                        time.sleep(5)
                    stop_servers(procs)
                    multihost_barrier(coord_host, coord_port, f"post_stop_{var_idx}", worker_id, timeout_s=600)
                    continue

            rec["server_ready_s"] = round(time.time() - t0, 1)
            rec["server_info"] = server_info(server_logs)
            if bench_base_url is None:
                rec["status"] = "SERVER_FAILED"
                rec["server_log_tail"] = server_logs[0].read_text(errors="replace")[-6000:] if server_logs[0].exists() else ""
                log(f"[{var['name']}] server did not become ready ({rec['server_ready_s']}s)")
                if is_var_multihost:
                    multihost_mark_done(coord_host, coord_port, var_idx, "failed")
                stop_servers(procs)
                if is_var_multihost:
                    multihost_barrier(coord_host, coord_port, f"post_stop_{var_idx}", worker_id, timeout_s=600)
                write_summary(out_dir, meta, results, worker_id=worker_id, nnodes=nnodes_plan)
                continue

            rec["bench_base_url"] = bench_base_url
            log(f"[{var['name']}] ready after {rec['server_ready_s']}s at {bench_base_url}")
            rec["sanity"] = sanity_generate(bench_base_url, base_sa.get("served_model_name", ""))
            log(f"[{var['name']}] sanity: {json.dumps(rec['sanity'])[:500]}")
            rec["status"] = "RUNNING"
            on_upd = lambda: write_summary(out_dir, meta, results, worker_id=worker_id, nnodes=nnodes_plan)
            on_upd()
            bench_extra = list(plan.get("bench_extra", [])) + list(var.get("bench_extra", []))
            execute_workload_list(
                rec,
                var.get("workloads", plan["workloads"]),
                bench_base_url,
                str(local),
                base_sa.get("served_model_name", ""),
                bench_extra,
                out_dir,
                cell_timeout_s,
                procs,
                server_logs,
                on_upd,
            )
            if rec["status"] == "RUNNING":
                rec["status"] = "DONE"
            rec["server_info"] = server_info(server_logs)
            on_upd()

            # Execute warm sub_passes (e.g. sampled T=0.6/T=1.0 or shared-prefix RadixCache) on the live server!
            for sp in var.get("sub_passes", []):
                if any(pr.poll() is not None for pr in procs):
                    break
                if sp.get("flush_cache", True):
                    flush_server_cache(bench_base_url)
                sp_rec = {
                    "name": sp["name"],
                    "desc": sp["desc"],
                    "chips_used": sp.get("chips_used", var.get("chips_used")),
                    "replicas": rec["replicas"],
                    "worker_id": worker_id,
                    "server_ready_s": 0.0,
                    "bench_base_url": bench_base_url,
                    "sanity": rec.get("sanity"),
                    "recipe": rec.get("recipe"),
                    "status": "RUNNING",
                    "cells": [],
                }
                results.append(sp_rec)
                on_upd()
                sp_extra = list(plan.get("bench_extra", [])) + list(sp.get("bench_extra", []))
                execute_workload_list(
                    sp_rec,
                    sp.get("workloads", var.get("workloads", plan["workloads"])),
                    bench_base_url,
                    str(local),
                    base_sa.get("served_model_name", ""),
                    sp_extra,
                    out_dir,
                    int(sp.get("cell_timeout_s", cell_timeout_s)),
                    procs,
                    server_logs,
                    on_upd,
                )
                if sp_rec["status"] == "RUNNING":
                    sp_rec["status"] = "DONE"
                sp_rec["server_info"] = server_info(server_logs)
                on_upd()

            if is_var_multihost:
                multihost_mark_done(coord_host, coord_port, var_idx, "done")
            stop_servers(procs)
            if is_var_multihost:
                multihost_barrier(coord_host, coord_port, f"post_stop_{var_idx}", worker_id, timeout_s=600)
        except Exception as exc:
            rec["status"] = f"ERROR: {type(exc).__name__}: {exc}"[:400]
            log(f"[{var['name']}] {rec['status']}")
            if is_var_multihost and is_var_leader:
                multihost_mark_done(coord_host, coord_port, var_idx, "error")
            stop_servers(procs)
            if is_var_multihost:
                try:
                    multihost_barrier(coord_host, coord_port, f"post_stop_{var_idx}", worker_id, timeout_s=300)
                except Exception:
                    pass
        if is_var_leader:
            write_summary(out_dir, meta, results, worker_id=worker_id, nnodes=nnodes_plan)

    if is_multihost_job:
        multihost_barrier(coord_host, coord_port, "all_done", worker_id, timeout_s=14400)
        time.sleep(2.0)
        if worker_id == 0:
            write_summary(out_dir, meta, results, worker_id=0, nnodes=nnodes_plan)
    log(f"sweep finished -> {out_dir}")
    return 0


