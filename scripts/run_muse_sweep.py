#!/usr/bin/env python3
"""SGLang-TorchTPU single-host serving sweep for the Meta Muse models (Glimmer-30B, Spark-816B-A42B).

Derived from scratch/sglang_tpu/run_sglang_tpu_single_host_sweep.py (same method), generalized to:
  * TPU v5p hosts (4 chips, 1 device per chip -> tp4) and TPU v7x hosts (4 chips x 2 TensorCores -> tp8),
  * a speculative-decoding draft checkpoint staged next to the target (DFLASH / MuseGlimmerAssistantModel),
  * a post-boot sanity generation (greedy chat completion) recorded with every variant,
  * a targeted process cleanup (the harness' own command line must never match the kill pattern).

For each server variant this:
  1. writes an SGLang TPU launch recipe under benchmark/tpu/recipe/configs/muse_custom/ that derives from the
     upstream validated base (_FP8_BASE_CONFIG + LIBTPU_FLAGS) and applies the plan/variant overrides,
  2. starts `python -m benchmark.tpu.launch_server` (FORCE_SINGLE_HOST=1) and waits for /health_generate,
  3. runs `python -m sglang.benchmark.serving` over an (input_len, output_len, concurrency) grid with fixed-length
     prompts (--random-range-ratio 1.0, ShareGPT text, EOS ignored so every request decodes exactly output_len),
  4. stops the server and appends every cell to summary.json / SUMMARY.md under --out-root/<tag>_<UTC ts>/.
A variant that fails to come up is recorded (with the tail of its server log) and the sweep moves on.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
import urllib.request

SGL_ROOT = Path("/workspace/sglang")
RECIPE_DIR = SGL_ROOT / "benchmark/tpu/recipe/configs/muse_custom"
KILL_PATTERN = r"sglang::|sglang\.launch_server|benchmark\.tpu\.launch_server|sglang\.benchmark\.serving"

RECIPE_TEMPLATE = '''"""Generated by run_muse_sweep.py: {name}."""
import json
from copy import deepcopy

from benchmark.tpu.recipe.configs.base import _FP8_BASE_CONFIG, LIBTPU_FLAGS

CONFIG = deepcopy(_FP8_BASE_CONFIG)
CONFIG["server_args"].update(json.loads({server_args!r}))
CONFIG["runtime_env"].update(json.loads({runtime_env!r}))
for _k in json.loads({drop_server_args!r}):
    CONFIG["server_args"].pop(_k, None)
_extra_libtpu = {extra_libtpu!r}
if _extra_libtpu:
    CONFIG["runtime_env"]["LIBTPU_INIT_ARGS"] = " ".join(LIBTPU_FLAGS + tuple(_extra_libtpu))
'''


def log(msg: str) -> None:
    print(f"[{dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}][muse-sweep] {msg}", flush=True)


def stage_model(gcs_uri: str, local_dir: Path) -> float:
    """Copies a checkpoint to host RAM (/dev/shm) once; every TP rank then reads local files."""
    marker = local_dir / ".staged"
    if marker.exists():
        return 0.0
    local_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    subprocess.run(
        ["gcloud", "storage", "cp", "-r", "--no-user-output-enabled", f"{gcs_uri.rstrip('/')}/*", str(local_dir)],
        check=True,
    )
    marker.write_text("ok\n")
    return time.time() - t0


def wait_ready(port: int, proc: subprocess.Popen, timeout_s: float) -> bool:
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if proc.poll() is not None:
            return False
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/health_generate", timeout=60) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            pass
        time.sleep(20)
    return False


def stop_server(proc: subprocess.Popen) -> None:
    if proc.poll() is None:
        try:
            os.killpg(proc.pid, signal.SIGTERM)
            proc.wait(timeout=120)
        except Exception:
            try:
                os.killpg(proc.pid, signal.SIGKILL)
            except Exception:
                pass
    subprocess.run(["pkill", "-9", "-f", KILL_PATTERN], check=False)
    time.sleep(30)  # let libtpu release the chips before the next variant


def sanity_generate(port: int, served_name: str) -> dict:
    """One greedy chat completion to show the served model produces coherent text."""
    body = {
        "model": served_name or "default",
        "messages": [{"role": "user", "content": "In one short sentence: what is the capital of France?"}],
        "max_tokens": 256,
        "temperature": 0,
    }
    req = urllib.request.Request(
        f"http://127.0.0.1:{port}/v1/chat/completions", data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=600) as resp:
            out = json.loads(resp.read().decode())
        msg = out["choices"][0]["message"]
        content = msg.get("content") or ""
        return {"ok": True, "latency_s": round(time.time() - t0, 2), "content": content[:600],
                "content_tail": content[-300:], "reasoning_content": (msg.get("reasoning_content") or "")[:600],
                "usage": out.get("usage")}
    except Exception as exc:  # recorded, not fatal
        return {"ok": False, "error": f"{type(exc).__name__}: {exc}"[:400]}


def server_info(server_log: Path) -> list[str]:
    keys = ("max_total_num_tokens", "KV Cache is allocated", "Memory pool end", "avail mem", "SWA", "max_running_requests",
            "Load weight end", "accept", "draft")
    lines = []
    try:
        for line in server_log.read_text(errors="replace").splitlines():
            if "TP0" in line and any(k in line for k in keys) and len(lines) < 25:
                lines.append(line[-400:])
    except Exception:
        pass
    return lines


def run_cell(port: int, tokenizer: str, served_name: str, inp: int, out: int, conc: int, out_file: Path,
             extra_args: list[str]) -> dict:
    nprompts = max(4 * conc, 8) if inp <= 16384 else max(2 * conc, 3)
    cmd = [
        sys.executable, "-m", "sglang.benchmark.serving",
        "--backend", "sglang",
        "--base-url", f"http://127.0.0.1:{port}",
        "--dataset-name", "random",
        "--random-input-len", str(inp),
        "--random-output-len", str(out),
        "--random-range-ratio", "1.0",
        "--num-prompts", str(nprompts),
        "--max-concurrency", str(conc),
        "--tokenizer", tokenizer,
        "--output-file", str(out_file),
        "--warmup-requests", "1",
        *extra_args,
    ]
    if served_name:
        cmd += ["--model", served_name]
    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=7200)
    row = {"input_len": inp, "output_len": out, "concurrency": conc, "num_prompts": nprompts,
           "return_code": proc.returncode, "wall_s": round(time.time() - t0, 1)}
    metrics = {}
    if out_file.exists():
        lines = [l for l in out_file.read_text().splitlines() if l.strip()]
        if lines:
            try:
                metrics = json.loads(lines[-1])
            except Exception:
                metrics = {}
    keep = (
        "completed", "duration", "request_throughput", "input_throughput", "output_throughput",
        "total_throughput", "mean_ttft_ms", "median_ttft_ms", "p99_ttft_ms", "mean_tpot_ms", "median_tpot_ms",
        "p99_tpot_ms", "mean_itl_ms", "median_itl_ms", "p99_itl_ms", "mean_e2e_latency_ms", "median_e2e_latency_ms",
        "accept_length", "spec_accept_length", "total_input_tokens", "total_output_tokens", "max_concurrency",
    )
    row["metrics"] = {k: metrics[k] for k in keep if k in metrics}
    if proc.returncode != 0 or not row["metrics"]:
        row["error_tail"] = (proc.stdout[-1500:] + "\n" + proc.stderr[-2500:]).strip()
    return row


def fmt(v, nd=1) -> str:
    return "-" if v is None else (f"{v:,.{nd}f}" if isinstance(v, (int, float)) else str(v))


def write_summary(out_dir: Path, meta: dict, variants: list[dict]) -> None:
    hw = meta.get("hardware", {})
    chips = int(hw.get("chips", 4))
    payload = {"updated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(), **meta, "variants": variants}
    (out_dir / "summary.json").write_text(json.dumps(payload, indent=2))
    md = [
        f"# {meta['title']}",
        "",
        f"- **Updated (UTC):** `{payload['updated_at_utc']}`",
        f"- **Hardware:** {hw.get('desc', '')}; engine `SGLang-TorchTPU` (`{meta.get('image', '')}`), "
        "single-host mode (`FORCE_SINGLE_HOST=1`).",
        f"- **Checkpoint:** `{meta['model_repo']}` (`{meta.get('model_gb', '?')}` GB).",
        "- **Method:** `python -m sglang.benchmark.serving --dataset-name random --random-range-ratio 1.0` "
        "(ShareGPT text truncated/repeated to the exact input length), every request decodes exactly `output_len` "
        "tokens (EOS ignored), server-default sampling unless the variant says otherwise; throughput is measured "
        "at the client over the whole run (4 x concurrency prompts, >= 8; 2 x concurrency for inputs > 16K).",
        "",
        "| Variant | Layout / precision | In / Out | Conc. | Req/s | Output tok/s | Output tok/s/chip | Total tok/s "
        "| TTFT p50 / p99 (ms) | TPOT p50 / p99 (ms) | Spec accept len | Status |",
        "|---|---|---|---:|---:|---:|---:|---:|---|---|---:|---|",
    ]
    for v in variants:
        if not v.get("cells"):
            md.append(f"| `{v['name']}` | {v['desc']} | - | - | - | - | - | - | - | - | - | `{v['status']}` |")
            continue
        for c in v["cells"]:
            m = c.get("metrics", {})
            otps = m.get("output_throughput")
            acc = m.get("accept_length", m.get("spec_accept_length"))
            status = "PASS" if m and c["return_code"] == 0 else f"FAIL(rc={c['return_code']})"
            md.append(
                f"| `{v['name']}` | {v['desc']} | `{c['input_len']}` / `{c['output_len']}` | {c['concurrency']} | "
                f"{fmt(m.get('request_throughput'), 3)} | {fmt(otps)} | {fmt(otps / chips if otps else None)} | "
                f"{fmt(m.get('total_throughput'))} | {fmt(m.get('median_ttft_ms'), 0)} / {fmt(m.get('p99_ttft_ms'), 0)} | "
                f"{fmt(m.get('median_tpot_ms'), 2)} / {fmt(m.get('p99_tpot_ms'), 2)} | {fmt(acc, 2)} | `{status}` |"
            )
    md += ["", "## Variant status / boot info", ""]
    for v in variants:
        md.append(f"- `{v['name']}`: **{v['status']}**, server ready after `{v.get('server_ready_s', '-')}` s"
                  + (f"; sanity: `{(v.get('sanity') or {}).get('content', '')[:160]!r}`" if v.get("sanity") else ""))
    (out_dir / "SUMMARY.md").write_text("\n".join(md) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True, help="JSON plan: model, hardware, variants, workloads")
    ap.add_argument("--out-root", default="/models/benchmark-results")
    ap.add_argument("--only", default="", help="Comma-separated variant names to run (in plan order)")
    ap.add_argument("--tag-suffix", default="", help="Appended to the plan tag (e.g. host name)")
    args = ap.parse_args()

    plan = json.loads(Path(args.plan).read_text())
    ts = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out_dir = Path(args.out_root) / f"{plan['tag']}{args.tag_suffix}_{ts}"
    out_dir.mkdir(parents=True, exist_ok=True)
    RECIPE_DIR.mkdir(parents=True, exist_ok=True)
    port = int(plan.get("port", 30000))
    meta = {k: plan[k] for k in ("title", "model_repo", "model_gb", "image", "hardware") if k in plan}
    meta["plan"] = plan
    meta["only"] = args.only
    meta["node"] = os.environ.get("NODE_NAME", "")
    results: list[dict] = []
    only = [s.strip() for s in args.only.split(",") if s.strip()]
    variants = plan["variants"]
    if only:
        by_name = {v["name"]: v for v in variants}
        variants = [by_name[n] for n in only if n in by_name]

    staged: dict[str, Path] = {}
    for var in variants:
        rec = {"name": var["name"], "desc": var["desc"], "status": "PENDING", "cells": []}
        results.append(rec)
        write_summary(out_dir, meta, results)
        proc = None
        try:
            gcs = var.get("model_gcs", plan["model_gcs"])
            draft_gcs = var.get("draft_gcs")
            needed = {gcs} | ({draft_gcs} if draft_gcs else set())
            for old_gcs, old_dir in list(staged.items()):  # keep only what this variant needs in host RAM
                if old_gcs not in needed:
                    subprocess.run(["rm", "-rf", str(old_dir)], check=False)
                    staged.pop(old_gcs)
            for uri in sorted(needed):
                if uri not in staged:
                    local = Path("/dev/shm/models") / uri.rstrip("/").split("/")[-1]
                    log(f"staging {uri} -> {local}")
                    secs = stage_model(uri, local)
                    staged[uri] = local
                    log(f"staged in {secs:.0f}s")
            local = staged[gcs]
            server_args = {"model_path": str(local), "port": port, **plan.get("server_args", {}),
                           **var.get("server_args", {})}
            if draft_gcs:
                server_args["speculative_draft_model_path"] = str(staged[draft_gcs])
                overrides = var.get("draft_config_overrides") or {}
                if overrides:  # patch the host-RAM copy only; the GCS checkpoint stays untouched
                    cfg_path = staged[draft_gcs] / "config.json"
                    cfg = json.loads(cfg_path.read_text())
                    changed = {k: v for k, v in overrides.items() if cfg.get(k) != v}
                    if changed:
                        cfg.update(changed)
                        cfg_path.write_text(json.dumps(cfg, indent=2))
                    rec["draft_config_overrides"] = overrides
                    log(f"[{var['name']}] draft config overrides applied: {changed or 'already present'}")
            runtime_env = {"FORCE_SINGLE_HOST": "1", **plan.get("runtime_env", {}), **var.get("runtime_env", {})}
            drop = list(plan.get("drop_server_args", [])) + list(var.get("drop_server_args", []))
            extra_libtpu = list(plan.get("extra_libtpu", [])) + list(var.get("extra_libtpu", []))
            mod = f"{var['name']}.py"
            (RECIPE_DIR / mod).write_text(
                RECIPE_TEMPLATE.format(
                    name=var["name"], server_args=json.dumps(server_args), runtime_env=json.dumps(runtime_env),
                    drop_server_args=json.dumps(drop), extra_libtpu=extra_libtpu,
                )
            )
            rec["recipe"] = (RECIPE_DIR / mod).read_text()
            server_log = out_dir / f"server_{var['name']}.log"
            log(f"[{var['name']}] launching server ({var['desc']})")
            t0 = time.time()
            with open(server_log, "w") as lf:
                proc = subprocess.Popen(
                    [sys.executable, "-m", "benchmark.tpu.launch_server", "--config",
                     f"recipe/configs/muse_custom/{mod}"],
                    cwd=str(SGL_ROOT), stdout=lf, stderr=subprocess.STDOUT, start_new_session=True,
                    env={**os.environ, "HEALTH_TIMEOUT": str(int(var.get("ready_timeout_s", 5400)))},
                )
                ready = wait_ready(port, proc, float(var.get("ready_timeout_s", 5400)))
                rec["server_ready_s"] = round(time.time() - t0, 1)
                rec["server_info"] = server_info(server_log)
                if not ready:
                    rec["status"] = "SERVER_FAILED"
                    rec["server_log_tail"] = server_log.read_text(errors="replace")[-6000:]
                    log(f"[{var['name']}] server did not become ready ({rec['server_ready_s']}s)")
                    stop_server(proc)
                    write_summary(out_dir, meta, results)
                    continue
                log(f"[{var['name']}] ready after {rec['server_ready_s']}s")
                rec["sanity"] = sanity_generate(port, server_args.get("served_model_name", ""))
                log(f"[{var['name']}] sanity: {json.dumps(rec['sanity'])[:500]}")
                rec["status"] = "RUNNING"
                write_summary(out_dir, meta, results)
                bench_extra = list(plan.get("bench_extra", [])) + list(var.get("bench_extra", []))
                for inp, out, concs in var.get("workloads", plan["workloads"]):
                    for conc in concs:
                        cell_file = out_dir / f"bench_{var['name']}_i{inp}_o{out}_c{conc}.jsonl"
                        log(f"[{var['name']}] bench in={inp} out={out} conc={conc}")
                        try:
                            cell = run_cell(port, str(local), server_args.get("served_model_name", ""), inp, out, conc,
                                            cell_file, bench_extra)
                        except subprocess.TimeoutExpired:
                            cell = {"input_len": inp, "output_len": out, "concurrency": conc, "return_code": -9,
                                    "metrics": {}, "error_tail": "client timeout"}
                        rec["cells"].append(cell)
                        m = cell.get("metrics", {})
                        log(f"[{var['name']}] -> rc={cell['return_code']} out_tok/s={m.get('output_throughput')} "
                            f"ttft_p50={m.get('median_ttft_ms')} tpot_p50={m.get('median_tpot_ms')} "
                            f"accept={m.get('accept_length', m.get('spec_accept_length'))}")
                        write_summary(out_dir, meta, results)
                        if proc.poll() is not None:
                            break
                    if proc.poll() is not None:
                        rec["status"] = "SERVER_DIED"
                        rec["server_log_tail"] = server_log.read_text(errors="replace")[-6000:]
                        break
                if rec["status"] == "RUNNING":
                    rec["status"] = "DONE"
                rec["server_info"] = server_info(server_log)
                stop_server(proc)
        except Exception as exc:  # keep the sweep going
            rec["status"] = f"ERROR: {type(exc).__name__}: {exc}"[:400]
            log(f"[{var['name']}] {rec['status']}")
            if proc is not None:
                stop_server(proc)
        write_summary(out_dir, meta, results)
    log(f"sweep finished -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
