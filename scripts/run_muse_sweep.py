def gcs_to_fuse_path(gcs_uri: str, fuse_root: str = "/models") -> Path:
    without_scheme = gcs_uri.replace("gs://", "", 1)
    rel = without_scheme.split("/", 1)[1] if "/" in without_scheme else ""
    return Path(fuse_root) / rel


def prefetch_gcsfuse_pagecache(model_dir: Path, workers: int = 16) -> float:
    """Warm Linux kernel page cache from GCSFuse in parallel (100% kernel-reclaimable RAM)."""
    files = sorted(model_dir.glob("*.safetensors"))
    if not files:
        return 0.0
    t0 = time.time()

    def _read_file(fp: Path) -> int:
        total = 0
        buf = bytearray(16 * 1024 * 1024)
        mv = memoryview(buf)
        with fp.open("rb", buffering=0) as f:
            while True:
                n = f.readinto(mv)
                if not n:
                    break
                total += n
        return total

    total_bytes = 0
    with ThreadPoolExecutor(max_workers=workers) as ex:
        for b in ex.map(_read_file, files):
            total_bytes += b
    dt_s = time.time() - t0
    gb = total_bytes / 1e9
    log(f"warmed page cache: {len(files)} shards ({gb:.1f} GB) in {dt_s:.1f}s ({gb / max(dt_s, 0.1):.2f} GB/s)")
    return dt_s


def stage_model(gcs_uri: str, local_dir: Path) -> float:
    marker = local_dir / ".staged"
    if marker.exists():
        return 0.0
    local_dir.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    subprocess.run(
        ["gcloud", "storage", "cp", "-r", "--no-user-output-enabled", f"{gcs_uri.rstrip('/')}/*", str(local_dir)],
        check=True,
    )
    marker.write_text("ok\n")
    return time.time() - t0


def start_coord_server(port: int, nnodes: int) -> ThreadingHTTPServer:
    """Lightweight TCP coordinator on worker 0 to avoid GCSFuse directory cache staleness."""
    lock = threading.Lock()
    barriers: dict[str, set[int]] = {}
    done_variants: dict[int, str] = {}

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, format: str, *args) -> None:  # noqa: A002
            return

        def _json(self, obj: dict) -> None:
            data = json.dumps(obj).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self) -> None:  # noqa: N802
            parsed = urllib.parse.urlparse(self.path)
            qs = urllib.parse.parse_qs(parsed.query)
            with lock:
                if parsed.path == "/barrier":
                    stage = qs["stage"][0]
                    w = int(qs["w"][0])
                    s = barriers.setdefault(stage, set())
                    s.add(w)
                    self._json({"arrived": len(s), "ready": len(s) >= nnodes})
                elif parsed.path == "/mark_done":
                    v = int(qs["v"][0])
                    st = qs.get("status", ["done"])[0]
                    done_variants[v] = st
                    self._json({"ok": True})
                elif parsed.path == "/is_done":
                    v = int(qs["v"][0])
                    self._json({"done": v in done_variants, "status": done_variants.get(v, "")})
                else:
                    self._json({"ok": True})

    srv = ThreadingHTTPServer(("0.0.0.0", port), Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


def multihost_barrier(coord_host: str, coord_port: int, stage: str, worker_id: int, timeout_s: float = 900.0) -> None:
    deadline = time.time() + timeout_s
    url = f"http://{coord_host}:{coord_port}/barrier?stage={urllib.parse.quote(stage)}&w={worker_id}"
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=5) as resp:
                data = json.loads(resp.read().decode())
                if data.get("ready"):
                    return
        except Exception:
            pass
        time.sleep(1.0)
    raise TimeoutError(f"multihost barrier '{stage}' timed out after {timeout_s}s")


def multihost_mark_done(coord_host: str, coord_port: int, var_idx: int, status: str) -> None:
    url = f"http://{coord_host}:{coord_port}/mark_done?v={var_idx}&status={urllib.parse.quote(status)}"
    for _ in range(10):
        try:
            with urllib.request.urlopen(url, timeout=5) as resp:
                if resp.status == 200:
                    return
        except Exception:
            time.sleep(1.0)


def multihost_is_done(coord_host: str, coord_port: int, var_idx: int) -> bool:
    url = f"http://{coord_host}:{coord_port}/is_done?v={var_idx}"
    try:
        with urllib.request.urlopen(url, timeout=5) as resp:
            return bool(json.loads(resp.read().decode()).get("done"))
    except Exception:
        return False


def wait_ready_any(base_urls: list[str], procs: list[subprocess.Popen], timeout_s: float) -> str | None:
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if any(p.poll() is not None for p in procs):
            return None
        for base_url in base_urls:
            try:
                with urllib.request.urlopen(f"{base_url}/health_generate", timeout=30) as resp:
                    if resp.status != 200:
                        continue
                with urllib.request.urlopen(f"{base_url}/v1/models", timeout=15) as mresp:
                    if mresp.status == 200:
                        return base_url
            except Exception:
                pass
        time.sleep(12)
    return None


def stop_servers(procs: list[subprocess.Popen]) -> None:
    for proc in procs:
        if proc is not None and proc.poll() is None:
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except Exception:
                pass
    for proc in procs:
        if proc is not None and proc.poll() is None:
            try:
                proc.wait(timeout=60)
            except Exception:
                try:
                    os.killpg(proc.pid, signal.SIGKILL)
                except Exception:
                    pass
    subprocess.run(["pkill", "-9", "-f", KILL_PATTERN], check=False)
    time.sleep(25)


def sanity_generate(base_url: str, served_name: str) -> dict:
    body = {
        "model": served_name or "default",
        "messages": [{"role": "user", "content": "In one short sentence: what is the capital of France?"}],
        "max_tokens": 256,
        "temperature": 0,
    }
    req = urllib.request.Request(
        f"{base_url}/v1/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=600) as resp:
            out = json.loads(resp.read().decode())
        msg = out["choices"][0]["message"]
        content = msg.get("content") or ""
        return {
            "ok": True,
            "latency_s": round(time.time() - t0, 2),
            "content": content[:600],
            "content_tail": content[-300:],
            "reasoning_content": (msg.get("reasoning_content") or "")[:600],
            "usage": out.get("usage"),
        }
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {exc}"[:400]}


def server_info(server_logs: list[Path]) -> list[str]:
    keys = (
        "max_total_num_tokens",
        "KV Cache is allocated",
        "Memory pool end",
        "avail mem",
        "SWA",
        "max_running_requests",
        "Load weight end",
        "normalized node rank",
        "accept",
        "draft",
    )
    lines = []
    for server_log in server_logs:
        try:
            for line in server_log.read_text(errors="replace").splitlines():
                if ("TP0" in line or "Schedule" in line or "normalized" in line) and any(k in line for k in keys):
                    lines.append(line[-400:])
                    if len(lines) >= 25:
                        return lines
        except Exception:
            pass
    return lines


def run_cell(
    base_url: str,
    tokenizer: str,
    served_name: str,
    inp: int,
    out: int,
    conc: int,
    out_file: Path,
    extra_args: list[str],
    timeout_s: int = 1500,
) -> dict:
    if inp >= 100000:
        nprompts = max(conc, 2)
    elif inp > 16384:
        nprompts = max(2 * conc, 3)
    else:
        nprompts = max(4 * conc, 8)
    ds_args = [] if "--dataset-name" in extra_args else ["--dataset-name", "random"]
    cmd = [
        sys.executable,
        "-m",
        "sglang.benchmark.serving",
        "--backend",
        "sglang",
        "--base-url",
        base_url,
        *ds_args,
        "--random-input-len",
        str(inp),
        "--random-output-len",
        str(out),
        "--random-range-ratio",
        "1.0",
        "--num-prompts",
        str(nprompts),
        "--max-concurrency",
        str(conc),
        "--tokenizer",
        tokenizer,
        "--output-file",
        str(out_file),
        "--warmup-requests",
        "1",
        *extra_args,
    ]
    if served_name:
        cmd += ["--model", served_name]
    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_s)
    row = {
        "input_len": inp,
        "output_len": out,
        "concurrency": conc,
        "num_prompts": nprompts,
        "return_code": proc.returncode,
        "wall_s": round(time.time() - t0, 1),
    }
    metrics = {}
    if out_file.exists():
        lines = [l for l in out_file.read_text().splitlines() if l.strip()]
        if lines:
            try:
                metrics = json.loads(lines[-1])
            except Exception:
                metrics = {}
    keep = (
        "completed",
        "duration",
        "request_throughput",
        "input_throughput",
        "output_throughput",
        "total_throughput",
        "mean_ttft_ms",
        "median_ttft_ms",
        "p99_ttft_ms",
        "mean_tpot_ms",
        "median_tpot_ms",
        "p99_tpot_ms",
        "mean_itl_ms",
        "median_itl_ms",
        "p99_itl_ms",
        "mean_e2e_latency_ms",
        "median_e2e_latency_ms",
        "accept_length",
        "spec_accept_length",
        "total_input_tokens",
        "total_output_tokens",
        "max_concurrency",
    )
    row["metrics"] = {k: metrics[k] for k in keep if k in metrics}
    if proc.returncode != 0 or not row["metrics"]:
        row["error_tail"] = (proc.stdout[-1500:] + "\n" + proc.stderr[-2500:]).strip()
    return row


